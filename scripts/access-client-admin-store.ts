import { createHash, randomUUID } from 'node:crypto';

type Audit = { operation: string; actor: string; reason: string; now: number };
function audit(actor: string, reason: string): Audit {
  if (
    !actor ||
    actor.length > 128 ||
    !reason ||
    reason.length > 512 ||
    /[\x00-\x1f\x7f]/.test(actor + reason)
  )
    throw new Error('invalid audit metadata');
  return { operation: randomUUID(), actor, reason, now: Math.floor(Date.now() / 1000) };
}
function id(value: string) {
  if (!/^[A-Za-z0-9_-]{1,128}$/.test(value)) throw new Error('invalid identifier');
  return value;
}
function secretHash(secret: string) {
  if (
    !/^[A-Za-z0-9_-]{43}$/.test(secret) ||
    Buffer.from(secret, 'base64url').length !== 32 ||
    Buffer.from(secret, 'base64url').toString('base64url') !== secret
  )
    throw new Error('secret must encode 32 random bytes');
  return createHash('sha256').update(secret).digest('base64url');
}
function callback(raw: string) {
  const url = new URL(raw);
  if (
    url.protocol !== 'https:' ||
    url.href !== raw ||
    url.username ||
    url.password ||
    url.port ||
    url.search ||
    url.hash ||
    !/^[a-z0-9-]+\.cloudflareaccess\.com$/.test(url.hostname) ||
    url.pathname !== '/cdn-cgi/access/callback'
  )
    throw new Error('invalid Access callback');
  return url;
}
function revision(n: number) {
  if (!Number.isSafeInteger(n) || n < 1) throw new Error('invalid expected revision');
  return n;
}
function guard(db: any, meta: Audit) {
  return db
    .prepare(
      'INSERT INTO atomic_guard(operation_id,passed) VALUES(?,CASE WHEN changes()=1 THEN 1 ELSE 0 END)',
    )
    .bind(meta.operation);
}
function done(db: any, meta: Audit) {
  return db.prepare('DELETE FROM atomic_guard WHERE operation_id=?').bind(meta.operation);
}
function secretAudit(db: any, meta: Audit, client: string, action: string, rev: number) {
  return db
    .prepare('INSERT INTO access_client_secret_audit VALUES(?,?,?,?,?,?,?)')
    .bind(meta.operation, client, action, rev, meta.actor, meta.reason, meta.now);
}
function emailAudit(
  db: any,
  meta: Audit,
  client: string,
  account: string,
  action: string,
  rev: number,
) {
  return db
    .prepare('INSERT INTO access_email_binding_audit VALUES(?,?,?,?,?,?,?,?)')
    .bind(meta.operation, client, account, action, rev, meta.actor, meta.reason, meta.now);
}

/** Caller must supply a secret generated by a cryptographic random source. */
export async function registerAccessClient(
  db: any,
  client: string,
  redirect: string,
  secret: string,
  method: 'client_secret_basic' | 'client_secret_post',
  actor: string,
  reason: string,
) {
  id(client);
  const uri = callback(redirect);
  const digest = secretHash(secret);
  const meta = audit(actor, reason);
  if (!['client_secret_basic', 'client_secret_post'].includes(method))
    throw new Error('invalid secret method');
  await db.batch([
    db
      .prepare(
        "INSERT INTO client(client_id,revision,active,client_type,auth_method,allow_missing_pkce,sector_identifier) VALUES(?,1,1,'web',?,0,?)",
      )
      .bind(client, method, uri.hostname),
    db
      .prepare('INSERT INTO client_redirect_uri(client_id,redirect_uri,active) VALUES(?,?,1)')
      .bind(client, uri.href),
    db
      .prepare('INSERT INTO client_secret(client_id,revision,active,secret_hash) VALUES(?,1,1,?)')
      .bind(client, digest),
    secretAudit(db, meta, client, 'register', 1),
  ]);
  return { client, operation: meta.operation };
}

export async function rotateAccessSecret(
  db: any,
  client: string,
  expected: number,
  secret: string | null,
  actor: string,
  reason: string,
) {
  id(client);
  revision(expected);
  const digest = secret === null ? null : secretHash(secret);
  const meta = audit(actor, reason);
  await db.batch([
    db
      .prepare(
        "UPDATE client_secret SET revision=revision+1,active=?,secret_hash=COALESCE(?,secret_hash) WHERE client_id=? AND revision=? AND active=1 AND EXISTS(SELECT 1 FROM client c WHERE c.client_id=client_secret.client_id AND c.active=1 AND c.client_type='web' AND c.auth_method IN ('client_secret_basic','client_secret_post') AND c.allow_missing_pkce=0)",
      )
      .bind(digest === null ? 0 : 1, digest, client, expected),
    guard(db, meta),
    secretAudit(db, meta, client, digest === null ? 'revoke' : 'rotate', expected + 1),
    done(db, meta),
  ]);
  return { client, revision: expected + 1, operation: meta.operation };
}

/** Operator must independently verify ownership of this exact address. */
export async function bindAccessEmail(
  db: any,
  client: string,
  account: string,
  email: string | null,
  expected: number,
  actor: string,
  reason: string,
) {
  id(client);
  id(account);
  if (!Number.isSafeInteger(expected) || expected < 0) throw new Error('invalid expected revision');
  if (email !== null && (!/^[\x21-\x7e]{3,254}$/.test(email) || !/^[^@]+@[^@]+$/.test(email)))
    throw new Error('invalid email');
  if (email === null && expected === 0) throw new Error('cannot revoke an absent binding');
  const meta = audit(actor, reason);
  const change =
    expected === 0
      ? db
          .prepare(
            "INSERT INTO access_email_binding(client_id,account_id,email,revision,active,verified_at) SELECT c.client_id,a.account_id,?,1,1,? FROM client c JOIN account_security a ON a.account_id=? WHERE c.client_id=? AND c.active=1 AND c.client_type='web' AND c.auth_method IN ('client_secret_basic','client_secret_post') AND c.allow_missing_pkce=0 AND a.active=1",
          )
          .bind(email, meta.now, account, client)
      : db
          .prepare(
            "UPDATE access_email_binding SET email=COALESCE(?,email),revision=revision+1,active=?,verified_at=CASE WHEN ? IS NULL THEN verified_at ELSE ? END WHERE client_id=? AND account_id=? AND revision=? AND EXISTS(SELECT 1 FROM client c JOIN account_security a ON a.account_id=access_email_binding.account_id WHERE c.client_id=access_email_binding.client_id AND c.active=1 AND c.client_type='web' AND c.auth_method IN ('client_secret_basic','client_secret_post') AND c.allow_missing_pkce=0 AND a.active=1)",
          )
          .bind(email, email === null ? 0 : 1, email, meta.now, client, account, expected);
  await db.batch([
    change,
    guard(db, meta),
    emailAudit(
      db,
      meta,
      client,
      account,
      expected === 0 ? 'bind' : email === null ? 'revoke' : 'replace',
      expected + 1,
    ),
    done(db, meta),
  ]);
  return { client, account, revision: expected + 1, operation: meta.operation };
}
