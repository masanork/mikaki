import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtempSync, readFileSync, readdirSync, rmSync, renameSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const lock = JSON.parse(readFileSync(join(root, 'scripts/fonts.lock.json'), 'utf8'));
const gjs = process.env.MIKAKI_GJS_DIR ?? join(homedir(), 'repo/gjs');
const python = process.env.MIKAKI_FONT_PYTHON ?? join(root, 'local/generated/font-venv/bin/python');
const check = process.argv.includes('--check');
assert.ok(
  process.argv.slice(2).every((arg) => arg === '--check'),
  'Usage: build-fonts.mjs [--check]',
);
const run = (command, args, options = {}) =>
  execFileSync(command, args, { cwd: root, encoding: 'utf8', ...options });
const hash = (path) => createHash('sha256').update(readFileSync(path)).digest('hex');
assert.equal(run('git', ['-C', gjs, 'rev-parse', 'HEAD']).trim(), lock.gjs_commit, 'gjs revision');
for (const [path, expected] of Object.entries(lock.gjs_files))
  assert.equal(hash(join(gjs, path)), expected, `Pinned gjs input changed: ${path}`);
assert.equal(run('wasm-pack', ['--version']).trim(), `wasm-pack ${lock.wasm_pack}`);
const rustEnv = { ...process.env, RUSTUP_TOOLCHAIN: lock.rust };
assert.ok(run('rustc', ['--version'], { env: rustEnv }).startsWith(`rustc ${lock.rust} `));
const versions = JSON.parse(
  run(python, [
    '-c',
    'import json,sys,fontTools,brotli,zopfli; print(json.dumps([".".join(map(str,sys.version_info[:2])),fontTools.__version__,brotli.__version__,zopfli.__version__]))',
  ]),
);
assert.deepEqual(
  versions,
  [lock.python, lock.fonttools, lock.brotli, lock.zopfli],
  'Install scripts/fonts-requirements.txt in a Python 3.12 venv',
);
run(python, ['scripts/download-font-sources.py'], { stdio: 'inherit' });
const temporary = mkdtempSync(join(root, 'local/generated/font-build-'));
const wasm = join(temporary, 'wasm');
const output = join(temporary, 'fonts');
try {
  // Remove host checkout paths from Rust panic locations; avoid an unpinned wasm-opt binary.
  const sysroot = run('rustc', ['--print', 'sysroot'], { env: rustEnv }).trim();
  run(
    'wasm-pack',
    [
      'build',
      join(gjs, 'crates/font-subsetter'),
      '--target',
      'bundler',
      '--release',
      '--no-opt',
      '--out-dir',
      wasm,
      '--',
      '--locked',
    ],
    {
      stdio: 'inherit',
      env: {
        ...rustEnv,
        CARGO_TARGET_DIR: join(root, 'local/generated/font-target'),
        CARGO_ENCODED_RUSTFLAGS: [
          `--remap-path-prefix=${gjs}=/gjs`,
          `--remap-path-prefix=${process.env.CARGO_HOME ?? join(homedir(), '.cargo')}=/cargo`,
          `--remap-path-prefix=${sysroot}=/rust`,
        ].join('\x1f'),
      },
    },
  );
  run(
    python,
    [
      'scripts/build-fonts.py',
      '--gjs',
      gjs,
      '--wasm-dir',
      wasm,
      '--work',
      join(temporary, 'work'),
      '--output',
      output,
    ],
    { stdio: 'inherit' },
  );
  for (const [path, expected] of Object.entries(lock.gjs_files))
    assert.equal(
      hash(join(gjs, path)),
      expected,
      `Pinned gjs input changed during generation: ${path}`,
    );
  if (check) {
    const committed = join(root, 'assets/fonts');
    const names = readdirSync(committed).sort();
    const regenerated = readdirSync(output).sort();
    assert.ok(
      regenerated.length === names.length &&
        regenerated.every((name, index) => name === names[index]),
      `Regenerated inventory differs (${regenerated.length} generated; ${names.length} committed)`,
    );
    for (const name of names)
      assert.equal(
        hash(join(output, name)),
        hash(join(committed, name)),
        `Regenerated bytes differ: ${name}`,
      );
    console.log(`Clean regeneration matches all ${names.length} committed files byte for byte.`);
  } else {
    const destination = join(root, 'assets/fonts');
    const backup = join(temporary, 'previous-fonts');
    renameSync(destination, backup);
    try {
      renameSync(output, destination);
    } catch (error) {
      renameSync(backup, destination);
      throw error;
    }
  }
} finally {
  rmSync(temporary, { recursive: true, force: true });
}
